/**
 * Finds your AI-generated images in public/images/ai/ and writes
 * src/data/aiImages.js, so the site uses them automatically.
 *
 * Name the files exactly as listed in AI-IMAGE-PROMPTS.md, e.g.
 *   public/images/ai/services/web-development.jpg
 *   public/images/ai/cases/pulsecare-telehealth.webp
 * (.jpg, .jpeg, .png, .webp and .avif all work). Any slot without a file
 * keeps its current illustration. Runs automatically before every build.
 */
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const root = process.cwd();
const dir = join(root, 'public', 'images', 'ai');
const exts = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif']);
const found = {};

const walk = (d) => {
  for (const name of readdirSync(d)) {
    const p = join(d, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (exts.has(extname(name).toLowerCase())) {
      const rel = relative(dir, p).replace(/\\/g, '/');
      found[rel.slice(0, -extname(rel).length)] = `/images/ai/${rel}`;
    }
  }
};
if (existsSync(dir)) walk(dir);

const out = `// Generated by scripts/scan-ai-images.mjs — do not edit by hand.
// Maps an image slot (see AI-IMAGE-PROMPTS.md) to the AI image you added.
export const aiImages = ${JSON.stringify(found, null, 2)};

/** The AI image for a slot if you've added one, otherwise the fallback. */
export const pickImage = (slot, fallback) => aiImages[slot] ?? fallback;
`;
writeFileSync(join(root, 'src', 'data', 'aiImages.js'), out);
console.log(`✔ AI images: ${Object.keys(found).length} found in public/images/ai`);
